#!/usr/bin/env python3
"""Mirror this repo's governing documentation into an openDesk XWiki.

One-directional by design: git is the source of truth, XWiki is a read-only
shop window. Nothing here ever reads a wiki page back into the repo, because
the moment editing can happen in two places the two drift and neither is
authoritative -- the failure this repo already hit once with DESIGN_LOG's
stale pointer to ~/blog-consistency-check/.

The tool is report-only unless --apply is passed. It also re-reads every page
it writes and compares it byte-for-byte against what it sent, rather than
trusting the HTTP status: this archive has been bitten before by a step that
reported success without checking (the daily chain's `git push` still echoes
"committed + pushed" whether or not the push worked).

Configuration comes from ~/.config/market-secrets/credentials.env, never from
the repo:

    XWIKI_BASE_URL=https://wiki.example.org        # openDesk XWiki root
    XWIKI_USER=some.user
    XWIKI_TOKEN=...                                # password or API token
    XWIKI_SPACE=masaladeutsch                      # optional, see --space

Usage:
    python3 tools/xwiki_mirror.py                  # dry run: show what would change
    python3 tools/xwiki_mirror.py --apply          # push the changed pages
    python3 tools/xwiki_mirror.py --self-test      # exercise push+verify against a local stub
"""
import argparse, base64, hashlib, http.server, json, os, pathlib, re, sys, threading
import urllib.error, urllib.parse, urllib.request
import xml.etree.ElementTree as ET

ROOT = str(pathlib.Path(__file__).resolve().parent.parent)
CREDS = pathlib.Path(os.path.expanduser("~/.config/market-secrets/credentials.env"))

# Explicit, not a glob. A glob would sweep in whatever lands in docs/ next,
# and this tool publishes to somewhere other people read.
MIRRORED = [
    "README.md",
    "CLAUDE.md",
    "MAINTENANCE.md",
    "DESIGN_LOG.md",
    "SEO_KEYWORDS.md",
    "docs/ACCOUNT_AUDIT.md",
    "docs/BLOGGER_API_RUNBOOK.md",
    "docs/COMMISSION_QUEUE.md",
    "docs/LITERATURE_SURVEY.md",
    "docs/REPO_ANALYSIS.md",
    "docs/SOURCE_REGISTER.md",
]

# Deliberately NOT mirrored, and why. Both are generated, both change every
# day, and both are large -- mirroring them would bury the hand-written docs
# in churn and make every wiki diff noise.
EXCLUDED = {
    "CHANGELOG.md": "generated by snapshot.py, one entry per run",
    "MASALADEUTSCH_ALL_POSTS_SUMMARY.md": "regenerated daily by build_md_summary.py",
}

XWIKI_SYNTAX = "markdown/1.2"


def creds():
    """Read config. Returns (base_url, user, token, space)."""
    if not CREDS.exists():
        sys.exit(f"missing {CREDS} -- see the module docstring for the four keys")
    text = CREDS.read_text()

    def get(name, required=True, default=None):
        m = re.search(rf"^{name}=(.*)$", text, re.M)
        if m and m.group(1).strip():
            return m.group(1).strip()
        if required:
            sys.exit(f"{name} not in {CREDS}")
        return default

    base = get("XWIKI_BASE_URL").rstrip("/")
    return base, get("XWIKI_USER"), get("XWIKI_TOKEN"), get("XWIKI_SPACE", False, "masaladeutsch")


def page_name(rel):
    """docs/REPO_ANALYSIS.md -> REPO_ANALYSIS. Flat namespace under one space:
    XWiki nested spaces would mirror the directory layout, but docs/ is one
    level deep and a flat list is easier to scan in the wiki index."""
    return pathlib.Path(rel).stem


def title_of(rel, body):
    """Prefer the document's own H1; fall back to the filename. A wiki index
    listing 'CLAUDE' next to 'README' is less useful than the real titles."""
    m = re.search(r"^#\s+(.+?)\s*$", body, re.M)
    return m.group(1).strip() if m else page_name(rel)


def page_url(base, space, name):
    q = urllib.parse.quote
    return f"{base}/rest/wikis/xwiki/spaces/{q(space)}/pages/{q(name)}"


def _auth_header(user, token):
    return "Basic " + base64.b64encode(f"{user}:{token}".encode()).decode()


def fetch(url, user, token):
    """GET a page. Returns (content, syntax) or (None, None) if absent."""
    req = urllib.request.Request(url, headers={
        "Authorization": _auth_header(user, token), "Accept": "application/xml"})
    try:
        raw = urllib.request.urlopen(req, timeout=30).read()
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None, None
        raise
    root = ET.fromstring(raw)
    ns = "{http://www.xwiki.org}"
    def text(tag):
        el = root.find(f"{ns}{tag}")
        return el.text if el is not None and el.text is not None else ""
    return text("content"), text("syntax")


def push(url, user, token, title, body, syntax):
    """PUT a page. Returns the HTTP status."""
    ns = "http://www.xwiki.org"
    page = ET.Element("page", xmlns=ns)
    ET.SubElement(page, "title").text = title
    ET.SubElement(page, "syntax").text = syntax
    ET.SubElement(page, "content").text = body
    payload = ET.tostring(page, encoding="utf-8")
    req = urllib.request.Request(url, data=payload, method="PUT", headers={
        "Authorization": _auth_header(user, token), "Content-Type": "application/xml"})
    return urllib.request.urlopen(req, timeout=30).status


def mirror(base, user, token, space, apply_changes, syntax=XWIKI_SYNTAX, out=sys.stdout):
    """Push every changed doc. Returns (pushed, skipped, problems)."""
    pushed, skipped, problems = [], [], []
    for rel in MIRRORED:
        src = pathlib.Path(ROOT) / rel
        if not src.exists():
            problems.append(f"{rel}: listed in MIRRORED but not in the repo")
            continue
        body = src.read_text(encoding="utf-8")
        name = page_name(rel)
        url = page_url(base, space, name)

        live, live_syntax = fetch(url, user, token)
        if live == body:
            skipped.append(rel)
            continue

        state = "new" if live is None else "changed"
        if not apply_changes:
            pushed.append(f"{rel} -> {space}.{name} ({state})")
            continue

        status = push(url, user, token, title_of(rel, body), body, syntax)

        # Read back rather than trusting the status code.
        back, back_syntax = fetch(url, user, token)
        if back != body:
            problems.append(
                f"{rel}: wrote {len(body)} chars, read back "
                f"{len(back) if back is not None else 'nothing'} -- page NOT verified")
            continue
        if back_syntax and back_syntax != syntax:
            problems.append(
                f"{rel}: asked for syntax {syntax!r} but the wiki stored {back_syntax!r} -- "
                f"the Markdown will render as literal text until that syntax is enabled")
        pushed.append(f"{rel} -> {space}.{name} ({state}, HTTP {status}, verified)")

    verb = "pushed" if apply_changes else "would push"
    print(f"{verb} {len(pushed)}  |  unchanged {len(skipped)}  |  problems {len(problems)}\n", file=out)
    for p in pushed:
        print(f"  {p}", file=out)
    if problems:
        print("\nPROBLEMS", file=out)
        for p in problems:
            print(f"  {p}", file=out)
    if not apply_changes and pushed:
        print("\n(dry run -- nothing was written. Re-run with --apply.)", file=out)
    return pushed, skipped, problems


# --------------------------------------------------------------------------
# Self-test: a stub XWiki that speaks just enough REST to exercise the real
# code path, so push + read-back verification can be proven without reaching
# the live instance (which this sandbox cannot reach anyway).
# --------------------------------------------------------------------------
class _StubXWiki(http.server.BaseHTTPRequestHandler):
    pages = {}
    corrupt = set()      # page names the stub will store wrongly, to prove verification bites
    coerce_syntax = None  # if set, the stub silently stores this syntax instead

    def log_message(self, *a):
        pass

    def _name(self):
        return urllib.parse.unquote(self.path.rstrip("/").split("/")[-1])

    def do_GET(self):
        name = self._name()
        if name not in self.pages:
            self.send_response(404); self.end_headers(); return
        content, syntax = self.pages[name]
        # Serialise properly rather than interpolating: the docs contain '<'
        # and '&', and a string-built response makes the stub -- not the tool
        # under test -- the thing that breaks.
        page = ET.Element("page", xmlns="http://www.xwiki.org")
        ET.SubElement(page, "title").text = "t"
        ET.SubElement(page, "syntax").text = syntax
        ET.SubElement(page, "content").text = content
        body = ET.tostring(page, encoding="utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/xml")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_PUT(self):
        name = self._name()
        raw = self.rfile.read(int(self.headers["Content-Length"]))
        root = ET.fromstring(raw)
        ns = "{http://www.xwiki.org}"
        content = root.find(f"{ns}content").text or ""
        syntax = root.find(f"{ns}syntax").text or ""
        if name in self.corrupt:
            content = content[:-5]           # truncate: verification must catch this
        if self.coerce_syntax:
            syntax = self.coerce_syntax      # silent downgrade: must be reported
        created = name not in self.pages
        self.pages[name] = (content, syntax)
        self.send_response(201 if created else 202); self.end_headers()


def self_test():
    _StubXWiki.pages, _StubXWiki.corrupt, _StubXWiki.coerce_syntax = {}, set(), None
    srv = http.server.HTTPServer(("127.0.0.1", 0), _StubXWiki)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    base = f"http://127.0.0.1:{srv.server_address[1]}"
    quiet = open(os.devnull, "w")
    ok = True

    def check(label, cond):
        nonlocal ok
        print(f"  {'PASS' if cond else 'FAIL'}  {label}")
        ok = ok and cond

    # 1. first run creates every page and verifies each one
    p, s, pr = mirror(base, "u", "t", "SP", True, out=quiet)
    check(f"first run pushes all {len(MIRRORED)} docs, no problems",
          len(p) == len(MIRRORED) and not pr and not s)

    # 2. second run is a no-op -- proves the read-back comparison, not a local cache
    p, s, pr = mirror(base, "u", "t", "SP", True, out=quiet)
    check("second run pushes nothing (idempotent)", not p and len(s) == len(MIRRORED) and not pr)

    # 3. dry run never writes
    _StubXWiki.pages.clear()
    p, s, pr = mirror(base, "u", "t", "SP", False, out=quiet)
    check("dry run reports every doc and writes nothing",
          len(p) == len(MIRRORED) and not _StubXWiki.pages)

    # 4. a wiki that stores something different is caught, not reported as success
    _StubXWiki.corrupt = {"CLAUDE"}
    p, s, pr = mirror(base, "u", "t", "SP", True, out=quiet)
    check("truncated write is caught by read-back verification",
          any("CLAUDE" in x and "NOT verified" in x for x in pr))
    _StubXWiki.corrupt = set()

    # 5. a silent syntax downgrade is reported
    _StubXWiki.pages.clear()
    _StubXWiki.coerce_syntax = "xwiki/2.1"
    p, s, pr = mirror(base, "u", "t", "SP", True, out=quiet)
    check("silent syntax coercion is reported",
          len(pr) == len(MIRRORED) and all("render as literal text" in x for x in pr))

    srv.shutdown()
    print("\nself-test:", "all checks passed" if ok else "FAILURES ABOVE")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--apply", action="store_true",
                    help="actually write to the wiki (default: report only)")
    ap.add_argument("--space", help="override XWIKI_SPACE")
    ap.add_argument("--syntax", default=XWIKI_SYNTAX,
                    help=f"page syntax to request (default: {XWIKI_SYNTAX})")
    ap.add_argument("--self-test", action="store_true",
                    help="exercise push and verification against a local stub wiki")
    args = ap.parse_args()

    if args.self_test:
        return self_test()

    base, user, token, space = creds()
    _, _, problems = mirror(base, user, token, args.space or space,
                            args.apply, args.syntax)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
