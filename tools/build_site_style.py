#!/usr/bin/env python3
"""Generate the single site-wide stylesheet from what the posts actually declare.

A hand-written list of "dark panel" class names cannot work: every post invented
its own (.chip, .kpi, .flow .t, .eyebrow …). So the list is derived from the
archive — every class whose own CSS gives it a dark background becomes a dark
panel in the module, everywhere, once.

    python3 tools/build_site_style.py          # writes templates/site-style.css

Re-run after adding posts that introduce new panel classes.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
POSTS = ROOT / "posts"
OUT = ROOT / "templates" / "site-style.css"

DARK_CUTOFF = 0.42   # mean luminance below this = a dark panel
LIGHT_CUTOFF = 0.72  # above this = a light panel


def lum(c):
    c = c.strip()
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            h = "".join(x * 2 for x in h)
        if len(h) < 6:
            return None
        try:
            r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        except ValueError:
            return None
    else:
        m = re.match(r"rgba?\(([^)]*)\)", c)
        if not m:
            return None
        parts = [p.strip() for p in m.group(1).replace("/", ",").split(",")]
        try:
            r, g, b = (float(parts[i]) for i in range(3))
        except (ValueError, IndexError):
            return None
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255


# Never treat these as panels: they are the document or a form control, and
# whitening their descendants whitens the page. This is the mineral-oil bug.
NEVER = {
    "body", "html", ":root", "*", "select", "input", "textarea", "option",
    "post-body", "artx", "post", "article", "main", "widget",
}


def classes_in(sel):
    """Class names in a selector, only if the selector is purely class-based."""
    if any(ch in sel for ch in "#>+~[") or "::" in sel:
        return []
    names = re.findall(r"\.([A-Za-z][\w-]*)", sel)
    if not names:
        return []
    # a compound like `.card .title` contributes its LAST class — that is the
    # element actually painted.
    return [names[-1]]


def collect():
    dark, light = {}, {}
    for f in sorted(POSTS.glob("*.html")):
        src = f.read_text(encoding="utf-8", errors="replace")
        css = "\n".join(re.findall(r"<style[^>]*>([\s\S]*?)</style>", src))
        if not css:
            continue
        rootvars = dict(re.findall(r"(--[\w-]+)\s*:\s*([^;}]+)", css))

        def resolve(v, depth=0):
            if depth > 3:
                return v
            m = re.search(r"var\((--[\w-]+)[^)]*\)", v)
            if m and m.group(1) in rootvars:
                return resolve(v.replace(m.group(0), rootvars[m.group(1)]), depth + 1)
            return v

        for m in re.finditer(r"([^{}]+)\{([^}]*)\}", css):
            sel, decl = m.group(1).strip(), m.group(2)
            if not sel or sel.startswith("@"):
                continue
            bg = re.search(r"background(?:-color|-image)?\s*:\s*([^;]+)", decl)
            if not bg:
                continue
            cols = re.findall(r"#[0-9a-fA-F]{3,8}|rgba?\([^)]*\)", resolve(bg.group(1)))
            lums = [x for x in (lum(c) for c in cols) if x is not None]
            if not lums:
                continue
            mean = sum(lums) / len(lums)
            for one in sel.split(","):
                for cls in classes_in(one.strip()):
                    if cls in NEVER:
                        continue
                    if mean < DARK_CUTOFF:
                        dark[cls] = dark.get(cls, 0) + 1
                    elif mean > LIGHT_CUTOFF:
                        light[cls] = light.get(cls, 0) + 1
    # a class declared dark anywhere is treated as dark everywhere; that is the
    # point of a single module. Ambiguous ones (declared both) follow the
    # majority, tie-breaking to dark so text stays white rather than invisible.
    for c in list(light):
        if c in dark and dark[c] >= light[c]:
            del light[c]
    for c in list(dark):
        if c in light and light[c] > dark[c]:
            del dark[c]
    return sorted(dark), sorted(light)


TEMPLATE = """/* ==========================================================================
   masaladeutsch — single site-wide style module.            v{ver}  {date}
   GENERATED by tools/build_site_style.py — do not hand-edit.
   --------------------------------------------------------------------------
   ONE stylesheet, installed once in the Blogger theme, applied to every page.
   It replaces the per-post light-locks and dark-panel guards that were being
   generated individually and that repeatedly produced light-on-light text.

   WHY IT LIVES IN THE THEME, NOT IN POSTS
   Post bodies carry their own <style> blocks written at different times with
   different palettes. Patching {n_posts} of them separately is what caused the
   regressions. This block is injected immediately before </body>, so it comes
   AFTER every post's CSS in document order and wins ties.

   THE ONE RULE
   Text is dark on light everywhere, EXCEPT inside a dark panel. The set of
   dark panels is not guessed — it is derived from every post in the archive:
   any class whose own CSS gives it a dark background is a dark panel here.
   {n_dark} dark classes, {n_light} light classes, from {n_posts} posts.

   Contrast targets (WCAG AA 4.5:1 for body text):
     #111 on #fff = 18.9:1   #8a4b08 on #fff = 6.6:1   #0b5394 on #fff = 8.6:1
     #fff on #182430 = 15.4:1   #cfe3ff on #182430 = 11.7:1
   ========================================================================== */

/* ---- 1. the page is light, always ------------------------------------- */
html, body {{ background: #fff !important; color-scheme: light !important; }}

/* ---- 2. the floor: nothing renders light-on-light ----------------------
   Everything below is more specific, so headings keep their accent and dark
   panels keep white text. The floor only catches what nothing else claims. */
.post-body * {{ color: #111 !important; }}

.post-body :is(h1,h2,h3,h4) {{ color: #8a4b08 !important; line-height: 1.3 !important; }}
.post-body a {{ color: #0b5394 !important; }}
.post-body a:hover {{ color: #06375f !important; }}
.post-body :is(small,.muted,.disclaimer,.src,.rs-src,.sig,.cnt,.gs-revised) {{
  color: #555 !important;
}}

/* ---- 3. light panels --------------------------------------------------- */
.post-body :is({LIGHT}) {{ background: #fdf7ec !important; border-color: #e8dcc4 !important; }}
.post-body :is({LIGHT}), .post-body :is({LIGHT}) * {{ color: #111 !important; }}

/* ---- 4. tables --------------------------------------------------------- */
.post-body table {{ width: 100%; border-collapse: collapse; margin: 14px 0; font-size: .88rem; }}
.post-body :is(th,td) {{
  border: 1px solid #e8dcc4; padding: 7px 9px; text-align: right;
  word-wrap: break-word; overflow-wrap: break-word;
}}
.post-body :is(th,td):first-child {{ text-align: left; }}
/* table header colour is set in section 8 — at this specificity a light-panel
   ancestor rule (.post-body :is(LIGHT) *, two classes) outranks `.post-body th *`
   (one class) and paints #111 on the dark header. */
.post-body th {{ background: #182430 !important; font-weight: 600; }}
.post-body tr:nth-child(even) {{ background: #fdf7ec; }}
.post-body tr:nth-child(even) td {{ color: #111 !important; }}

/* ---- 5. typography ----------------------------------------------------- */
.post-body, .post-body :is(p,li,td,th,h1,h2,h3,blockquote) {{
  font-family: Georgia, 'Times New Roman', serif;
}}
.post-body {{ line-height: 1.6; }}

/* ---- 6. nothing scrolls the page sideways ------------------------------ */
.post-body {{ overflow-x: hidden; }}
.post-body :is(.tw,.table-wrap) {{ overflow-x: auto; }}
.post-body :is(img,svg,canvas) {{ max-width: 100%; height: auto; }}

/* ---- 7. legacy overrides this module replaces -------------------------- */
@media all {{
  body {{ background: #fff !important; }}
  .post-body {{ background: transparent !important; }}
}}

/* ---- 8. dark panels — MUST BE LAST -------------------------------------
   Placed at the end so it beats sections 3-5 at equal specificity. Putting
   it earlier made contrast WORSE (437 failures vs 167): the light-panel and
   table rules re-claimed the text colour inside dark panels. Order is load-
   bearing here.                                                            */
.post-body :is({DARK}) {{ background: #182430 !important; border-color: #2a3a4a !important; }}
.post-body :is({DARK}), .post-body :is({DARK}) * {{ color: #fff !important; }}
.post-body :is({DARK}) a {{ color: #cfe3ff !important; }}

/* anything nested inside a dark panel stays dark, including light panels
   and striped table rows */
.post-body :is({DARK}) :is({LIGHT},table,thead,tbody,tr,td,th) {{
  background: #1e2c3a !important; border-color: #2a3a4a !important;
}}
.post-body :is({DARK}) :is({LIGHT},table,thead,tbody,tr,td,th),
.post-body :is({DARK}) :is({LIGHT},table,thead,tbody,tr,td,th) * {{
  color: #fff !important;
}}

/* Table headers, last and deliberately over-specific. `.post-body:is(.post-body)`
   counts as two classes, so this beats `.post-body :is({{LIGHT}}) *` on a header
   that happens to sit inside a light-classed wrapper. */
.post-body:is(.post-body) :is(th,thead th),
.post-body:is(.post-body) :is(th,thead th) * {{ color: #fff !important; }}
.post-body:is(.post-body) :is(th,thead th) {{ background: #182430 !important; }}
"""


def main():
    dark, light = collect()
    if not dark:
        sys.exit("no dark panel classes found — refusing to write an empty module")
    n_posts = len(list(POSTS.glob("*.html")))
    css = TEMPLATE.format(
        ver="1.1.0", date="2026-08-06", n_posts=n_posts,
        n_dark=len(dark), n_light=len(light),
        DARK=",".join("." + c for c in dark),
        LIGHT=",".join("." + c for c in light) or ".gs-none",
    )
    OUT.write_text(css, encoding="utf-8")
    print(f"{len(dark)} dark classes, {len(light)} light classes, from {n_posts} posts")
    print(f"dark : {', '.join(dark[:24])}{' …' if len(dark) > 24 else ''}")
    print(f"light: {', '.join(light[:16])}{' …' if len(light) > 16 else ''}")
    print(f"wrote {OUT} ({len(css):,} bytes)")


if __name__ == "__main__":
    main()
